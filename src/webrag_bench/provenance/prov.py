"""Export attestations as W3C PROV-O (JSON-LD).

Mapping: an attestation's output is a prov:Entity, generated by a prov:Activity (the
tool call) associated with a prov:Agent (the issuer); `derived_from` becomes
prov:wasDerivedFrom between entities. The signature is kept as a non-PROV property.
"""

from __future__ import annotations

from typing import Any

from webrag_bench.provenance.attestation import Attestation

CONTEXT = {
    "prov": "http://www.w3.org/ns/prov#",
    "webrag": "https://github.com/pm-mendes/webrag-r2a-bench/ns#",
    "xsd": "http://www.w3.org/2001/XMLSchema#",
}


def _entity(att_id: str) -> str:
    return f"webrag:output/{att_id}"


def to_prov_jsonld(attestations: list[Attestation]) -> dict[str, Any]:
    graph: list[dict[str, Any]] = []
    agents: set[str] = set()
    for att in attestations:
        activity_id = f"webrag:activity/{att.id}"
        agent_id = f"webrag:agent/{att.issuer}"
        if agent_id not in agents:
            agents.add(agent_id)
            graph.append({"@id": agent_id, "@type": "prov:Agent", "webrag:party": att.issuer})
        graph.append(
            {
                "@id": activity_id,
                "@type": "prov:Activity",
                "prov:wasAssociatedWith": {"@id": agent_id},
                "webrag:tool": att.activity["tool"],
                "webrag:argumentsDigest": att.activity["arguments_digest"],
                **(
                    {"prov:endedAtTime": {"@value": att.issued_at, "@type": "xsd:dateTime"}}
                    if att.issued_at
                    else {}
                ),
            }
        )
        graph.append(
            {
                "@id": _entity(att.id),
                "@type": "prov:Entity",
                "prov:wasGeneratedBy": {"@id": activity_id},
                "prov:wasAttributedTo": {"@id": agent_id},
                "prov:wasDerivedFrom": [{"@id": _entity(p)} for p in att.derived_from],
                "webrag:outputDigest": att.output_digest,
                "webrag:signature": att.signature,
            }
        )
    return {"@context": CONTEXT, "@graph": graph}
